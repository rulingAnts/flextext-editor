#!/usr/bin/env node
/* Builds docs/js/vendor/langtags-names.js: one language name per BCP-47 language subtag, taken from
 * SIL International's langtags.json. Issue #68.
 *
 * Seth, 2026-09-11: "What we want is the user to manually enter the writing system code, and then if
 * it matches a language that langtags.json recognizes, then display that language name after the ws
 * code box." And the constraint every reader of this table must keep: "We don't want to make it easy
 * for the user to skip noticing and checking their writing system code. By offering something that
 * looks automatic but actually isn't."
 *
 *   curl -sSLo /tmp/langtags.json https://ldml.api.sil.org/langtags.json
 *   node tools/build-langtags-names.mjs /tmp/langtags.json
 *
 * WHY A BUILT TABLE AND NOT THE LIVE FILE: ldml.api.sil.org sends no Access-Control-Allow-Origin
 * header (checked 2026-09-11), so a page cannot fetch it at all; these apps must work offline; and
 * the whole file is 5.4 MB for what is, here, one name per language.
 *
 * WHICH SUBTAGS GET A NAME: only ones a FLEx writing-system code can actually begin with.
 *   rank 0  an entry whose canonical tag IS the bare subtag            fau, id, yue
 *   rank 1  a bare equivalent in an entry's `tags`                     cmn ≡ zh-CN, zsm ≡ ms
 *   rank 2  the first subtag of a longer canonical tag                 sgn from sgn-…
 * ⚠ NEVER the first subtag of an extended-language form in `tags` (ar-aao, zh-yue). That subtag is
 * the MACROLANGUAGE, so keying on it names `ar` after whichever Arabic variety happened to come last:
 * 55 subtags collided that way when measured.
 * ⚠ NEVER an ISO 639-3 code that BCP-47 does not use (ind, eng). FLEx writes `id` and `en`, so a name
 * shown beside `ind` would tell a researcher their code is fine when FLEx holds a different one.
 * ⚠ NEVER the deprecated two-letter codes (in, iw, ji, jw, mo, bh, tw), for the same reason.
 *
 * The langtags license (MIT, SIL International) travels beside the output as langtags.LICENSE. */
import { readFileSync, writeFileSync } from 'node:fs';

const SRC = 'https://ldml.api.sil.org/langtags.json';
const OUT = new URL('../docs/js/vendor/langtags-names.js', import.meta.url);

const file = process.argv[2];
if (!file) {
  console.error('usage: node tools/build-langtags-names.mjs <path to langtags.json>\n'
    + `  get it with: curl -sSLo /tmp/langtags.json ${SRC}`);
  process.exit(2);
}
const data = JSON.parse(readFileSync(file, 'utf8'));
if (!Array.isArray(data)) throw new Error('langtags.json: expected an array of entries');

const version = data.find((e) => e && e.tag === '_version') || {};
const entries = data.filter((e) => e && typeof e.tag === 'string' && !e.tag.startsWith('_') && e.name);
const canonical = new Set(entries.map((e) => e.tag.split('-')[0]));

const best = new Map();   // subtag -> [rank, name]
const offer = (key, rank, name) => {
  if (!/^[a-z]{2,3}$/.test(key)) return;
  const had = best.get(key);
  if (!had || rank < had[0]) best.set(key, [rank, name]);
};
for (const e of entries) {
  offer(e.tag, 0, e.name);
  for (const t of e.tags || []) {
    if (t.includes('-')) continue;                      // only bare equivalents, never ar-aao
    if (t.length === 2 && !canonical.has(t)) continue;  // a deprecated two-letter code (in, iw, …)
    offer(t, 1, e.name);
  }
  offer(e.tag.split('-')[0], 2, e.name);
}

const names = Object.fromEntries([...best].sort(([a], [b]) => (a < b ? -1 : 1)).map(([k, [, n]]) => [k, n]));

// A changed file format must fail here, loudly, rather than ship a table that names nothing.
for (const [k, want] of [['fau', 'Fayu'], ['id', 'Indonesian'], ['en', 'English'], ['tpi', 'Tok Pisin']]) {
  if (names[k] !== want) throw new Error(`sanity: ${k} should be "${want}", got ${JSON.stringify(names[k])}`);
}
for (const k of ['ind', 'eng', 'in', 'qaa']) {
  if (k in names) throw new Error(`sanity: ${k} must not be a key, because FLEx never writes it`);
}

const count = Object.keys(names).length;
writeFileSync(OUT, `/* GENERATED by tools/build-langtags-names.mjs. Do not edit by hand: re-run the tool.
 *
 * One name per BCP-47 language subtag (${count}), from SIL International's langtags.json
 * (${SRC}, api ${version.api || '?'}, dated ${version.date || '?'}).
 * MIT license: see langtags.LICENSE beside this file. Loaded only when a settings form shows a
 * writing-system code box; see languageNameIn() in ../typing.js. */
export const LANGTAGS_DATE = ${JSON.stringify(version.date || '')};
export default JSON.parse(${JSON.stringify(JSON.stringify(names))});
`);
console.log(`wrote docs/js/vendor/langtags-names.js: ${count} subtags, langtags ${version.date || '?'}`);
